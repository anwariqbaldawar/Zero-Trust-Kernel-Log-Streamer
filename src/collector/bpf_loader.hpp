// bpf_loader.hpp - libbpf lifecycle management and policy-map manipulation for
// the xSypher-Stream collector.
//
// The loader owns the generated libbpf skeleton (`xsypher_bpf`), decides
// whether BPF-LSM programs can be loaded on this kernel, and exposes
// thread-safe methods that translate Python control commands into kernel map
// mutations.
#pragma once

#include <cstdint>
#include <mutex>
#include <string>
#include <vector>

#include <bpf/libbpf.h>

#include "xsypher_abi.h"

struct xsypher_bpf;  // generated by `bpftool gen skeleton xsypher.bpf.o`

namespace xsypher {

/// Configuration knobs derived from the collector CLI.
struct LoaderOptions {
    bool enforce_inline = false;  ///< --enforce  => config_map[0] = 1
    bool block_imds = false;      ///< --block-imds => pre-block 169.254.169.254
    bool verbose = false;         ///< --verbose => libbpf debug logging
    bool allow_lsm_fallback = true;  ///< retry load without BPF-LSM programs
};

/// Result of a map update/delete, surfaced for logging and JSON stats.
struct MapResult {
    bool ok = false;
    int err = 0;
    std::string message;
};

class BpfLoader {
public:
    BpfLoader() = default;
    ~BpfLoader();

    BpfLoader(const BpfLoader&) = delete;
    BpfLoader& operator=(const BpfLoader&) = delete;

    /// Open, load and attach the BPF object.  Never throws; on failure `error`
    /// describes what went wrong.  If the kernel has no BPF-LSM support (or
    /// booted without `lsm=bpf`), the loader transparently retries with only
    /// the tracepoint programs enabled and sets `lsm_available()` to false.
    bool load_and_attach(const LoaderOptions& options, std::string& error);

    /// Detach everything and free the skeleton.  Idempotent.
    void unload();

    /// True between a successful load_and_attach() and unload().
    bool loaded() const noexcept { return skel_ != nullptr; }

    /// True when the kernel accepted the lsm/* programs.
    bool lsm_available() const noexcept { return lsm_available_; }

    /// File descriptor of the events ring buffer map, or -1.
    int ringbuf_fd() const noexcept { return ringbuf_fd_; }

    /// Number of attached programs (tracepoints + LSM hooks).
    std::size_t attached_count() const noexcept { return links_.size(); }

    /// Human readable description of the kernel support state.
    std::string status_line() const;

    // -- policy map mutations (thread safe) -------------------------------- //
    MapResult quarantine_pid(std::uint32_t tgid, std::uint8_t action = QUARANTINE_BLOCK);
    MapResult unquarantine_pid(std::uint32_t tgid);
    MapResult quarantine_cgroup(std::uint64_t cgroup_id,
                                std::uint8_t action = QUARANTINE_BLOCK);
    MapResult unquarantine_cgroup(std::uint64_t cgroup_id);
    MapResult block_ipv4(std::uint32_t ipv4_network_order, std::uint8_t reason = 1);
    MapResult unblock_ipv4(std::uint32_t ipv4_network_order);
    MapResult set_enforcement_mode(std::uint32_t mode);

    /// Heartbeat / fail-closed / tamper-protection control plane (ABI v3).
    MapResult set_heartbeat(std::uint64_t heartbeat_ns);
    MapResult set_fail_closed(bool enabled);
    MapResult set_shutdown_token(std::uint32_t token);
    MapResult protect_pid(std::uint32_t tgid, std::uint32_t token = 0);
    MapResult unprotect_pid(std::uint32_t tgid);
    MapResult register_runtime_comm(const char* comm);
    MapResult register_inode(std::uint64_t ino, std::uint32_t dev);
    MapResult update_ringbuf_drops(std::uint64_t drops);

    /// Snapshot of the per-CPU metric counters, summed over all CPUs.
    /// Index 0..METRIC_MAX-1; returns an empty vector on failure.
    std::vector<std::uint64_t> read_metrics() const;

    /// Last libbpf error observed by attach, for diagnostics.
    const std::string& last_error() const noexcept { return last_error_; }

private:
    bool open_object(std::string& error);
    bool load_object(bool with_lsm, std::string& error);
    bool attach_programs(std::string& error);
    void destroy_skeleton();
    bool set_autoload_for_lsm(bool enable);
    void apply_runtime_defaults_locked();

    // Non-locking map mutations used by apply_runtime_defaults_locked() (which
    // runs while mutex_ is already held) and by the public wrappers below.
    MapResult register_runtime_comm_locked(const char* comm);
    MapResult register_inode_locked(std::uint64_t ino, std::uint32_t dev);
    MapResult protect_pid_locked(std::uint32_t tgid, std::uint32_t token);

    struct xsypher_bpf* skel_ = nullptr;
    std::vector<bpf_link*> links_{};
    mutable std::mutex mutex_{};
    LoaderOptions options_{};
    bool lsm_available_ = false;
    bool libbpf_logging_ = false;
    int ringbuf_fd_ = -1;
    std::string last_error_{};
};

/// Process-wide libbpf log callback.  Installed once from load_and_attach().
void install_libbpf_logging(bool verbose);

}  // namespace xsypher
